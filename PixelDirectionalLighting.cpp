//=========================================================================================================
// インクルード
//=========================================================================================================
#include "PixelDirectionalLighting.h"


//=========================================================================================================
// 初期化処理
//=========================================================================================================
void PixelDirectionalLighting::Init(void)
{
	PolygonModel::Init();

	//構造体初期化
	m_Position = XMFLOAT3(0.0f + 0.5 * 1, 0.5f, 0.0f);
};

//=========================================================================================================
// 終了処理
//=========================================================================================================
void PixelDirectionalLighting::Finalize(void)
{
	PolygonModel::Uninit();
}

//=========================================================================================================
// 更新処理
//=========================================================================================================
void PixelDirectionalLighting::Update(void)
{
	PolygonModel::Update();
}

//=========================================================================================================
// 描画処理
//=========================================================================================================
void PixelDirectionalLighting::Draw(void)
{
	PolygonModel::Draw();
}