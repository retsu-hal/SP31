//================================================================
//	インクルード
//================================================================
#include"PixelLightingBlinnPhong.h"

//================================================================
//	グローバル変数
//================================================================

//================================================================
//	初期化処理
//================================================================
void PixelLightingBlinnPhong::Init(void)
{
	PolygonModel::Init();
	
	//構造体初期化
	m_Position = XMFLOAT3(0.0f + 0.5 * 2, 0.5f, 0.0f);

	// ライト構造体の初期化
	XMVECTOR dir = XMVectorSet(0.0f, -1.0f, 1.0f, 0.0f);
	dir = XMVector3Normalize(dir);
	XMStoreFloat4(&m_Light.Direction, dir); // 光のベクトル
	m_Light.Diffuse = XMFLOAT4(0.8f, 0.8f, 0.8f, 1.0f); // 光の色
	m_Light.Ambient = XMFLOAT4(0.5f, 0.3f, 0.3f, 1.0f); // 環境光
}

//================================================================
//	終了処理
//================================================================
void PixelLightingBlinnPhong::Uninit(void)
{
	PolygonModel::Uninit();
}

//================================================================
//	更新処理
//================================================================
void PixelLightingBlinnPhong::Update(void)
{
	PolygonModel::Update();
}

//================================================================
//	描画処理
//================================================================
void PixelLightingBlinnPhong::Draw(void)
{
	PolygonModel::Draw();
	
}