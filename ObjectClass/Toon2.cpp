//==============================================================================
//インクルード
//==============================================================================
#include "Toon2.h"
#include "texture.h"

//==============================================================================
// 初期化処理
//==============================================================================
void Toon2::Init(void)
{
	PolygonModel::Init();

	m_Position = XMFLOAT3(0.5f, 0.5f, 0.0f);

	// パラメータ初期値
	m_Parameter = XMFLOAT4(0.5f, 0.0f, 0.0f, 0.0f);	// x:ランプのV座標（縦は固定）

	m_TexIDRamp = TextureLoad(GetRampTexturePath());

	// ライト構造体の初期化
	XMVECTOR dir = XMVectorSet(0.0f, -1.0f, 1.0f, 0.0f);
	dir = XMVector3Normalize(dir);
	XMStoreFloat4(&m_Light.Direction, dir);
	m_Light.Position = XMFLOAT4(0.0f, 1.0f, 0.0f, 1.0f);
	m_Light.Diffuse = XMFLOAT4(0.9f, 0.9f, 0.9f, 1.0f);
	m_Light.Ambient = XMFLOAT4(0.3f, 0.3f, 0.3f, 1.0f);
	m_Light.PointLightParam = XMFLOAT4(3.0f, 0.0f, 0.0f, 1.0f);
}

//==============================================================================
// 終了処理
//==============================================================================
void Toon2::Uninit(void)
{
	PolygonModel::Uninit();
}

//==============================================================================
// 更新処理
//==============================================================================
void Toon2::Update(void)
{
	PolygonModel::Update();
}

//==============================================================================
// 描画処理
//==============================================================================
void Toon2::Draw(void)
{

	ID3D11ShaderResourceView* tex = GetTexture(m_TexIDRamp);
	GetDeviceContext()->PSSetShaderResources(1, 1, &tex);

	PolygonModel::Draw();
}

//==============================================================================
// ImGui描画
//==============================================================================
void Toon2::DrawImGuiExtra()
{
	ImGui::SeparatorText("Toon2");
	ImGui::SliderFloat("Texture V", &m_Parameter.x, 0.0f, 1.0f, "%.4f");
}
